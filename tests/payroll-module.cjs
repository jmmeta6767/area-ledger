'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const html=read('gateway/public/payroll.html');
const root=read('gateway/public/index.html');
const sw=read('gateway/public/sw.js');

assert.match(html,/<title>AREA Ledger \| เงินเดือนพนักงานรายวัน<\/title>/);
assert.match(html,/const KEY='area-ledger-payroll-v1';/);
assert.ok(!html.includes("localStorage.setItem('site-ledger-v1'"),'Do not write to existing Ledger state');
assert.match(html,/href="\/"[^>]*aria-label="กลับหน้าหลัก AREA Ledger"/);
const script=html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script,'Payroll page script missing');
new vm.Script(script[1],{filename:'payroll-inline.js'});
const begin=script[1].indexOf('function getTotals(');
const end=script[1].indexOf('function setTab(');
assert.ok(begin>0&&end>begin,'Pay calculation engine missing');
const code=script[1].slice(begin,end)+'\ngetTotals("p1","2026-10")';
const attendance={'p1__2026-10-17':{employeeId:'p1',date:'2026-10-17',status:'work',wage:650},'p1__2026-10-18':{employeeId:'p1',date:'2026-10-18',status:'off',wage:0},'p1__2026-09-01':{employeeId:'p1',date:'2026-09-01',status:'work',wage:100}};
const db={attendance,advances:[{employeeId:'p1',date:'2026-10-17',amount:300},{employeeId:'p1',date:'2026-09-01',amount:20}]};
const ctx={db,decimal:n=>Math.round((n+Number.EPSILON)*100)/100};
assert.deepEqual(JSON.parse(JSON.stringify(vm.runInNewContext(code,ctx))),{earned:650,advanced:300,balance:350,present:1,off:1});
attendance['p1__2026-10-17'].status='off';attendance['p1__2026-10-17'].wage=0;
assert.equal(vm.runInNewContext(code,ctx).balance,-300);
attendance['p1__2026-10-17'].status='work';attendance['p1__2026-10-17'].wage=700;
assert.equal(vm.runInNewContext(code,ctx).balance,400);
assert.match(root,/\['payroll','calculator','เงินเดือนพนักงาน'/);
assert.match(root,/if\(a==='payrollOpen'\)\{window.location.assign\('\/payroll.html'\);return;\}/);
assert.match(sw,/CORE=.*'payroll.html'/);
assert.match(sw,/navCacheKey=.*'\/payroll.html'/);
assert.match(sw,/c.put\(navigation\?navCacheKey:e.request/);
console.log('PASS payroll module contract: totals, advances, isolation, navigation, PWA cache');
